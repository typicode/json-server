import { test } from "node:test";
import assert from "node:assert/strict";
import {
  existsSync,
  mkdtempDisposableSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { DatabaseSync } from "node:sqlite";
import { tmpdir } from "node:os";
import path from "node:path";

import type { Dataset } from "./json_types.ts";
import type { ResourceSchema } from "./schema.ts";
import { dumpDataset, JsonSource, schemaFileOf, writeFileAtomically } from "./json_source.ts";
import { DatasetError, type SourceOptions } from "./source.ts";
import { Store, StoreError } from "./store.ts";

const dirs: string[] = [];
test.after(() => {
  for (const dir of dirs) rmSync(dir, { recursive: true, force: true });
});

/** A temporary `db.json` holding `dataset`, with `schema` as `db.schema.sql` next to it when given. */
function makeFiles(dataset: Dataset, schema?: string): { file: string; schemaFile: string } {
  const dir = mkdtempSync(path.join(tmpdir(), "json-server-json-"));
  dirs.push(dir);
  const file = path.join(dir, "db.json");
  writeFileSync(file, JSON.stringify(dataset));
  const schemaFile = path.join(dir, "db.schema.sql");
  if (schema !== undefined) writeFileSync(schemaFile, schema);
  return { file, schemaFile };
}

function load(dataset: Dataset, schema?: string, options?: SourceOptions): Store {
  return new Store(new JsonSource(makeFiles(dataset, schema).file, options));
}

const throwsDataset = (fn: () => unknown, message: string | RegExp): void =>
  assert.throws(
    fn,
    (error: unknown) =>
      error instanceof DatasetError &&
      (typeof message === "string" ? error.message === message : message.test(error.message)),
  );

const blog: Dataset = {
  posts: [{ id: 1, title: "Hello", draft: false, tags: ["a"], meta: { rank: 1 }, views: 10 }],
  comments: [{ id: 1, body: "Nice", postId: 1 }],
};

test("schemaFileOf swaps the extension for .schema.sql in the same directory", () => {
  assert.equal(schemaFileOf("db.json"), "db.schema.sql");
  assert.equal(schemaFileOf("data/blog.json"), path.join("data", "blog.schema.sql"));
  assert.equal(schemaFileOf("/tmp/x/db"), "/tmp/x/db.schema.sql");
});

test("the first load generates the schema file: tables, columns and types, no constraints", () => {
  const { file, schemaFile } = makeFiles(blog);
  new JsonSource(file);

  assert.equal(
    readFileSync(schemaFile, "utf8"),
    `-- Generated by JSON Server from ${file}: its tables, columns and types.
-- Edit freely (REFERENCES, NOT NULL, UNIQUE, CHECK). JSON Server only appends to this
-- file: the CREATE TABLE of a resource it finds in the data and not here.

CREATE TABLE "posts" (
  "id" INTEGER PRIMARY KEY,
  "title" TEXT,
  "draft" BOOLEAN,
  "tags" ARRAY,
  "meta" JSON,
  "views" REAL
);

CREATE TABLE "comments" (
  "id" INTEGER PRIMARY KEY,
  "body" TEXT,
  "postId" REAL
);
`,
  );
});

test("the generated schema file reads back to the same data and is not rewritten", () => {
  const { file, schemaFile } = makeFiles(blog);
  new JsonSource(file);
  const generated = readFileSync(schemaFile, "utf8");

  const store = new Store(new JsonSource(file));
  assert.deepEqual(store.list("posts"), blog.posts);
  assert.deepEqual(store.list("comments"), blog.comments);
  assert.equal(store.list("posts")[0]?.draft, false);
  assert.equal(readFileSync(schemaFile, "utf8"), generated);
});

test("an empty resource has no property: it takes {} and its columns come from the schema file", () => {
  const { file, schemaFile } = makeFiles({ users: [], posts: blog.posts });
  const store = new Store(new JsonSource(file));
  assert.deepEqual(store.list("users"), []);
  assert.match(
    readFileSync(schemaFile, "utf8"),
    /CREATE TABLE "users" \(\n  "id" INTEGER PRIMARY KEY\n\);/,
  );

  assert.deepEqual(store.create("users", {}), { id: 1 });
  assert.deepEqual(store.replace("users", 1, { id: 1 }), { id: 1 });
  assert.throws(() => store.create("users", { name: "x" }), /unknown property/);

  // A property added by hand needs its column: the reload says which line adds it.
  writeFileSync(file, JSON.stringify({ users: [{ id: 1, name: "Ada" }], posts: blog.posts }));
  assert.throws(() => store.create("users", {}), /add it to its CREATE TABLE:\n {2}"name" TEXT/);
  writeFileSync(
    schemaFile,
    readFileSync(schemaFile, "utf8").replace(
      'CREATE TABLE "users" (\n  "id" INTEGER PRIMARY KEY',
      'CREATE TABLE "users" (\n  "id" INTEGER PRIMARY KEY,\n  "name" TEXT',
    ),
  );
  assert.deepEqual(store.list("users"), [{ id: 1, name: "Ada" }]);
});

test("a resource the schema file does not declare is inferred and appended to it", () => {
  const lines: string[] = [];
  const { file, schemaFile } = makeFiles(blog);
  const store = new Store(new JsonSource(file, { log: (line) => lines.push(line) }));
  const generated = readFileSync(schemaFile, "utf8");

  writeFileSync(file, JSON.stringify({ ...blog, tags: [{ id: 1, name: "sqlite", hot: true }] }));
  assert.deepEqual(store.list("tags"), [{ id: 1, name: "sqlite", hot: true }]);
  assert.equal(
    readFileSync(schemaFile, "utf8"),
    `${generated}\nCREATE TABLE "tags" (\n  "id" INTEGER PRIMARY KEY,\n  "name" TEXT,\n  "hot" BOOLEAN\n);\n`,
  );
  assert.deepEqual(lines, [
    `created ${schemaFile}`,
    `added "tags" to ${schemaFile}`,
    `reloaded ${file}`,
  ]);

  // Our own append is not an edit to reload; the file now declares everything.
  assert.deepEqual(store.resources(), ["comments", "posts", "tags"]);
  assert.equal(lines.length, 3);
});

test("a property left out of a POST takes the column's DEFAULT, a PUT makes it null", () => {
  const store = load(
    { posts: [{ id: 1, title: "Hello", views: 3 }] },
    `CREATE TABLE posts (id INTEGER PRIMARY KEY, title TEXT NOT NULL, views REAL DEFAULT 0);`,
  );
  assert.deepEqual(store.create("posts", { title: "New" }), { id: 2, title: "New", views: 0 });
  assert.deepEqual(store.replace("posts", 2, { id: 2, title: "New" }), {
    id: 2,
    title: "New",
    views: null,
  });
  assert.throws(
    () => store.create("posts", { views: 1 }),
    (error: unknown) =>
      error instanceof StoreError &&
      error.status === 400 &&
      error.errors[0]?.field === "title" &&
      error.errors[0]?.message === "must not be null",
  );
});

test("the schema file may hold indexes, triggers, views and an FTS table, kept across reloads", () => {
  const { file } = makeFiles(
    { posts: [{ id: 1, title: "Hello", views: 1 }] },
    `CREATE TABLE "posts" (
       "id" INTEGER PRIMARY KEY,
       "title" TEXT NOT NULL,
       "views" REAL DEFAULT 0,
       "createdAt" TEXT DEFAULT (datetime('now')),
       "slug" TEXT GENERATED ALWAYS AS (lower("title")) VIRTUAL
     );
     CREATE INDEX "posts_views" ON "posts"("views");
     CREATE VIEW "popular" AS SELECT "id", "title" FROM "posts" WHERE "views" > 0;
     CREATE VIRTUAL TABLE "posts_fts" USING fts5("title");
     CREATE TRIGGER "posts_ai" AFTER INSERT ON "posts" BEGIN
       INSERT INTO "posts_fts"(rowid, "title") VALUES (NEW."id", NEW."title");
     END;`,
  );
  const store = new Store(new JsonSource(file));

  // Only the plain table is a resource; the generated column is not a property.
  assert.deepEqual(store.resources(), ["posts"]);
  const created = store.create("posts", { title: "Fresh Post" });
  assert.deepEqual(Object.keys(created), ["id", "title", "views", "createdAt"]);
  assert.equal(created.views, 0);
  assert.match(String(created.createdAt), /^\d{4}-\d{2}-\d{2} /);

  // The trigger fed the FTS table, the view and the generated column answer through QUERY.
  assert.deepEqual(
    store
      .query(`SELECT rowid FROM "posts_fts" WHERE "posts_fts" MATCH 'fresh'`)
      .rows.map((r) => r.rowid),
    [created.id],
  );
  assert.deepEqual(
    store.query(`SELECT "slug" FROM "posts" ORDER BY "id"`).rows.map((r) => r.slug),
    ["hello", "fresh post"],
  );
  assert.equal(store.query(`SELECT count(*) AS n FROM "popular"`).rows[0]?.n, 1);

  // A reload drops and recreates everything, shadow tables included, and the rows go
  // through the trigger again: the FTS table is rebuilt from the data.
  writeFileSync(
    file,
    JSON.stringify({
      posts: [
        { id: 1, title: "Hello", views: 1 },
        { id: 2, title: "Two", views: 0 },
      ],
    }),
  );
  assert.equal(store.list("posts").length, 2);
  assert.equal(store.query(`SELECT count(*) AS n FROM "posts_fts"`).rows[0]?.n, 2);
});

test("rows may come in any order; a foreign key to a missing row is refused, naming the row", () => {
  const schema = `CREATE TABLE comments (id INTEGER PRIMARY KEY, body TEXT, postId INTEGER REFERENCES posts(id));`;
  const store = load(
    { comments: [{ id: 1, body: "Nice", postId: 1 }], posts: [{ id: 1, title: "Hello" }] },
    schema,
  );
  assert.equal(store.list("comments").length, 1);

  const { file } = makeFiles({ comments: [{ id: 3, body: "Orphan", postId: 99 }] }, schema);
  throwsDataset(
    () => new JsonSource(file),
    `${file}: comments[0].postId: no row with id 99 in "posts"`,
  );
});

test("a declared table is the truth: its relation holds, its column order is kept", () => {
  const store = load(
    blog,
    `CREATE TABLE comments (id INTEGER PRIMARY KEY, postId INTEGER NOT NULL REFERENCES posts(id) ON DELETE CASCADE, body TEXT);`,
  );
  assert.deepEqual(store.list("comments"), [{ id: 1, postId: 1, body: "Nice" }]);

  store.remove("posts", 1);
  assert.deepEqual(store.list("comments"), []);
});

test("a table only the schema file declares is an empty resource, saved to the file", () => {
  const { file } = makeFiles(blog, `CREATE TABLE tags (id INTEGER PRIMARY KEY, name TEXT);`);
  const store = new Store(new JsonSource(file));

  assert.deepEqual(store.resources(), ["comments", "posts", "tags"]);
  assert.deepEqual(store.list("tags"), []);

  store.create("tags", { name: "sqlite" });
  assert.deepEqual(Object.keys(JSON.parse(readFileSync(file, "utf8"))), [
    "posts",
    "comments",
    "tags",
  ]);
});

test("a property that is not a column of its declared table is refused, with the column to add", () => {
  const { file, schemaFile } = makeFiles(
    { posts: [{ id: 1, title: "Hello", views: 3 }] },
    `CREATE TABLE posts (id INTEGER PRIMARY KEY, title TEXT);`,
  );
  throwsDataset(
    () => new JsonSource(file),
    `${file}: posts.views: not a column of "posts" in ${schemaFile}, add it to its CREATE TABLE:\n` +
      `  "views" REAL`,
  );
});

test("a value that does not fit its declared column type is refused", () => {
  const { file, schemaFile } = makeFiles(
    { posts: [{ id: 1, title: "Hello", draft: "no" }] },
    `CREATE TABLE posts (id INTEGER PRIMARY KEY, title TEXT, draft BOOLEAN);`,
  );
  throwsDataset(
    () => new JsonSource(file),
    `${file}: posts[0].draft: must be a boolean or null, as declared in ${schemaFile}`,
  );
});

test("a constraint of the declared table is enforced on load, naming the row", () => {
  const { file } = makeFiles(
    {
      posts: [
        { id: 1, title: "a" },
        { id: 2, title: "a" },
      ],
    },
    `CREATE TABLE posts (id INTEGER PRIMARY KEY, title TEXT UNIQUE);`,
  );
  throwsDataset(
    () => new JsonSource(file),
    `${file}: posts[1]: UNIQUE constraint failed: posts.title`,
  );
});

test("invalid SQL in the schema file is reported with its name", () => {
  const { file, schemaFile } = makeFiles(blog, `CREATE TABL posts (id INTEGER PRIMARY KEY);`);
  throwsDataset(() => new JsonSource(file), new RegExp(`^${schemaFile}: .*syntax error`));
});

test("a resource whose declared table has no id INTEGER PRIMARY KEY is refused", () => {
  const { file, schemaFile } = makeFiles(
    { posts: [{ id: 1, title: "Hello" }] },
    `CREATE TABLE posts (id TEXT PRIMARY KEY, title TEXT);`,
  );
  throwsDataset(
    () => new JsonSource(file),
    `${file}: posts: its table in ${schemaFile} is not a resource, give it an "id" INTEGER PRIMARY KEY column`,
  );
});

test("an edit of the schema file is picked up by the next operation", () => {
  const lines: string[] = [];
  const { file, schemaFile } = makeFiles(blog);
  const store = new Store(new JsonSource(file, { log: (line) => lines.push(line) }));
  assert.deepEqual(store.list("comments"), blog.comments);

  writeFileSync(
    schemaFile,
    `CREATE TABLE comments (id INTEGER PRIMARY KEY, body TEXT, postId INTEGER REFERENCES posts(id));`,
  );
  assert.throws(() => store.create("comments", { body: "x", postId: 99 }), /no row with id 99/);
  // The rewritten file lost "posts": it is inferred again and appended back.
  assert.deepEqual(lines, [
    `created ${schemaFile}`,
    `added "posts" to ${schemaFile}`,
    `reloaded ${schemaFile}`,
  ]);
});

test("a broken schema file edit makes every operation fail until fixed", () => {
  const { file, schemaFile } = makeFiles(blog);
  const store = new Store(new JsonSource(file));
  const good = readFileSync(schemaFile, "utf8");

  writeFileSync(
    schemaFile,
    "CREATE TABLE posts (id INTEGER PRIMARY KEY, title TEXT, draft BOOLEAN);",
  );
  assert.throws(() => store.list("posts"), /not usable.*CREATE TABLE/s);
  assert.throws(() => store.create("posts", { title: "x" }), /not usable.*CREATE TABLE/s);

  writeFileSync(schemaFile, good);
  store.create("posts", { title: "x", draft: true, tags: [], meta: {}, views: 0 });
  assert.equal(store.list("posts").length, 2);
});

test("dumpDataset keeps schema order and converts values back to JSON types", () => {
  using db = new DatabaseSync(":memory:");
  db.exec(
    `CREATE TABLE "posts" ("id" INTEGER PRIMARY KEY, "title" TEXT, "draft" INTEGER, "tags" TEXT, "meta" TEXT, "views" REAL)`,
  );
  db.exec(`CREATE TABLE "comments" ("id" INTEGER PRIMARY KEY, "body" TEXT)`);
  db.exec(`INSERT INTO "posts" VALUES (2, 'World', 0, '["b"]', NULL, 1.5)`);
  db.exec(`INSERT INTO "posts" VALUES (1, 'Hello', 1, '["a"]', '{"rank":1}', 10)`);
  db.exec(`INSERT INTO "comments" VALUES (1, 'Nice')`);

  const schema = new Map<string, ResourceSchema>([
    [
      "posts",
      new Map([
        ["title", "string"],
        ["draft", "boolean"],
        ["tags", "array"],
        ["meta", "object"],
        ["views", "number"],
      ]),
    ],
    ["comments", new Map([["body", "string"]])],
  ]);

  const dataset = dumpDataset(db, schema);

  assert.deepEqual(Object.keys(dataset), ["posts", "comments"]);
  assert.deepEqual(dataset, {
    posts: [
      { id: 1, title: "Hello", draft: true, tags: ["a"], meta: { rank: 1 }, views: 10 },
      { id: 2, title: "World", draft: false, tags: ["b"], meta: null, views: 1.5 },
    ],
    comments: [{ id: 1, body: "Nice" }],
  });
  assert.deepEqual(Object.keys(dataset.posts[0]), [
    "id",
    "title",
    "draft",
    "tags",
    "meta",
    "views",
  ]);
});

test("writeFileAtomically writes the content and leaves no temp file", () => {
  using dir = mkdtempDisposableSync(path.join(tmpdir(), "json-server-"));
  const file = path.join(dir.path, "db.json");

  writeFileAtomically(file, "one\n");
  assert.equal(readFileSync(file, "utf8"), "one\n");
  assert.deepEqual(readdirSync(dir.path), ["db.json"]);

  writeFileAtomically(file, "two\n");
  assert.equal(readFileSync(file, "utf8"), "two\n");
});

test("writeFileAtomically throws when the file cannot be written and leaves nothing behind", () => {
  using dir = mkdtempDisposableSync(path.join(tmpdir(), "json-server-"));
  const file = path.join(dir.path, "absent", "db.json");

  assert.throws(() => writeFileAtomically(file, ""), /ENOENT/);
  assert.equal(existsSync(path.join(dir.path, "absent")), false);
});
